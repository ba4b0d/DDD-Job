def populate_seo_descriptions(db):
    from app.models import Product
    products = db.query(Product).all()
    updated = 0
    for p in products:
        p_code = (p.product_id or "").upper().strip()
        if p_code in SEO_DESCRIPTIONS:
            target_desc = SEO_DESCRIPTIONS[p_code]
            if not (p.notes or "").strip():
                p.notes = target_desc
                updated += 1
    if updated > 0:
        db.commit()
        print(f"Auto-seeded SEO descriptions for {updated} products.")
